#!/usr/bin/env electron
/**
 * Concealed-marker verification — REQUIRES A REAL macOS OR WINDOWS DESKTOP.
 *
 * This answers the one question the headless environment cannot: when a real
 * password manager copies a password, can Electron see the marker that says
 * "do not record this"?
 *
 * Cliptide's strongest privacy guarantee depends on the answer. Until this has
 * been run on both platforms, that guarantee is UNVERIFIED on macOS and
 * Windows and must not be claimed.
 *
 *   npx electron scripts/verify-concealed.js
 *
 * Then, in order:
 *   1. Copy ordinary text from a text editor.
 *   2. Copy a password from 1Password / Bitwarden / Keeper / Apple Passwords.
 *   3. Copy ordinary text again.
 *
 * SAFETY: this script never prints clipboard content. It prints format names,
 * byte lengths, and booleans only. Copy a throwaway password anyway.
 */

import { app, clipboard } from 'electron';
import os from 'node:os';
import { detectConcealedMarkers, expectedMarkersFor } from '../src/clipboard/markers.js';

const PROBE_FORMATS = [
  'org.nspasteboard.ConcealedType',
  'org.nspasteboard.TransientType',
  'org.nspasteboard.AutoGeneratedType',
  'org.nspasteboard.source',
  'ExcludeClipboardContentFromMonitorProcessing',
  'CanIncludeInClipboardHistory',
  'x-kde-passwordManagerHint',
  'application/x-nspasteboard-concealed',
];

const DURATION_MS = Number(process.env.CLIPTIDE_PROBE_SECONDS ?? 120) * 1000;
const observations = [];
let lastSignature = null;

function safely(fn) {
  try {
    return fn();
  } catch (err) {
    return `<threw: ${err.message.slice(0, 60)}>`;
  }
}

function snapshot() {
  const text = safely(() => clipboard.readText());
  const formats = safely(() => clipboard.availableFormats());

  const probes = {};
  for (const format of PROBE_FORMATS) {
    const has = safely(() => clipboard.has(format));
    probes[format] = {
      has,
      bytes: has === true ? safely(() => clipboard.readBuffer(format)?.length ?? 0) : 0,
    };
  }

  return {
    at: new Date().toISOString(),
    // Length only. Never the content.
    textLength: typeof text === 'string' ? text.length : 0,
    availableFormats: formats,
    probes,
    detectedMarkers: safely(() => detectConcealedMarkers(clipboard, process.platform)),
  };
}

function report(observation, index) {
  console.log(`\n--- clipboard change #${index} (${observation.at}) ---`);
  console.log(`  text length:       ${observation.textLength} chars  [content never printed]`);
  console.log(`  availableFormats:  ${JSON.stringify(observation.availableFormats)}`);

  const visible = Object.entries(observation.probes).filter(([, v]) => v.has === true);
  if (visible.length === 0) {
    console.log('  has() probes:      none of the known markers are present');
  } else {
    for (const [format, v] of visible) {
      console.log(`  has() probe:       ${format}  -> true (${v.bytes} bytes)`);
    }
  }

  const markers = observation.detectedMarkers;
  console.log(
    `  ENGINE VERDICT:    ${
      Array.isArray(markers) && markers.length > 0
        ? `CONCEALED -> would NOT be recorded  ${JSON.stringify(markers)}`
        : 'not concealed -> WOULD be recorded'
    }`,
  );
}

app.whenReady().then(() => {
  console.log(`\nCliptide concealed-marker probe (M1.1)`);
  console.log(`platform=${process.platform} ${process.arch} (${os.release()})`);
  console.log(`electron=${process.versions.electron}`);
  console.log(`markers conventional here: ${JSON.stringify(expectedMarkersFor(process.platform))}`);
  console.log(`(all known markers are probed regardless of platform)`);
  console.log(`\nNothing is stored and no clipboard content is printed — lengths only.`);
  console.log(`\nListening for ${DURATION_MS / 1000}s. Do this, in order:`);
  console.log(`  1. copy ordinary text from a text editor`);
  console.log(`  2. copy a THROWAWAY password from your password manager`);
  console.log(`  3. copy ordinary text again`);
  console.log(`\nPASS = step 2 reports "CONCEALED -> would NOT be recorded".\n`);

  const timer = setInterval(() => {
    const observation = snapshot();
    const signature = JSON.stringify([
      observation.textLength,
      observation.availableFormats,
      Object.entries(observation.probes).map(([k, v]) => [k, v.has]),
    ]);
    if (signature === lastSignature) return;
    lastSignature = signature;
    observations.push(observation);
    report(observation, observations.length);
  }, 500);

  setTimeout(() => {
    clearInterval(timer);

    const anyMarkerSeen = observations.some(
      (o) => Array.isArray(o.detectedMarkers) && o.detectedMarkers.length > 0,
    );

    console.log(`\n=== RESULT ===`);
    console.log(`  platform            ${process.platform} ${process.arch}`);
    console.log(`  electron            ${process.versions.electron}`);
    console.log(`  clipboard changes   ${observations.length}`);
    console.log(`  concealed observed  ${anyMarkerSeen}`);
    console.log(
      `\n  ${
        anyMarkerSeen
          ? 'OVERALL: PASS — Electron sees the concealed marker on this platform'
          : 'OVERALL: FAIL or INCONCLUSIVE — no marker observed. If you did copy from a\n           password manager, Electron cannot see its marker here and the native\n           addon in docs/M1-SPIKE.md section 7 is required.'
      }\n`,
    );

    console.log(`===CLIPTIDE_CONCEALED_JSON===`);
    console.log(
      JSON.stringify(
        {
          platform: process.platform,
          arch: process.arch,
          osRelease: os.release(),
          electron: process.versions.electron,
          expectedMarkers: expectedMarkersFor(process.platform),
          observations,
          anyConcealedMarkerObserved: anyMarkerSeen,
          verdict: anyMarkerSeen
            ? 'CONFIRMED: Electron can see a concealed marker on this platform'
            : 'NOT CONFIRMED: no concealed marker was observed — either none was copied, or Electron cannot see it',
        },
        null,
        2,
      ),
    );
    process.exitCode = anyMarkerSeen ? 0 : 1;
    app.quit();
  }, DURATION_MS);
});

app.on('window-all-closed', () => {});
